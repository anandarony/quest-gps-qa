"""Reporting: before/after comparison, financial impact and markdown reports.

SYNTHETIC financial assumptions (documented, not real rates):
  advertiser rate = USD 0.80 per eligible km;  driver payout = 40 % of billed amount.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

from .defect_detector import (ADVERTISER_RATE_USD_PER_KM, DRIVER_PAYOUT_SHARE, DEFECTS,
                              ablation_deltas, anomaly_scan, detect_defects)
from .distance_calculator import EngineConfig, driver_day_totals, process

ROOT = Path(__file__).resolve().parents[1]


def load_pings(path: Path | str | None = None) -> pd.DataFrame:
    path = Path(path) if path else ROOT / "data" / "synthetic_gps_pings.csv"
    return pd.read_csv(path, dtype=str, keep_default_na=False)


def build_before_after(pings: pd.DataFrame, baseline_daily: pd.DataFrame, cfg: EngineConfig | None = None,
                       reason_threshold_km: float = 0.005) -> pd.DataFrame:
    """One row per driver and report date: original vs corrected km, difference, reason, money."""
    cfg = cfg or EngineConfig()
    corrected = driver_day_totals(process(pings, cfg).daily).rename(columns={"km": "corrected_km"})
    original = driver_day_totals(baseline_daily).rename(columns={"km": "original_km"})
    df = original.merge(corrected, on=["driver_id", "report_date"], how="outer").fillna({"original_km": 0.0, "corrected_km": 0.0})
    df["difference_km"] = df["original_km"] - df["corrected_km"]
    df["difference_pct"] = (df["difference_km"] / df["corrected_km"].where(df["corrected_km"] > 0) * 100).round(2)
    deltas = ablation_deltas(pings, cfg)
    reasons = []
    for r in df.itertuples():
        parts = []
        for did in sorted(deltas, key=lambda k: -abs(deltas[k].get((r.driver_id, r.report_date), 0.0))):
            v = float(deltas[did].get((r.driver_id, r.report_date), 0.0))
            if abs(v) >= reason_threshold_km:
                parts.append(f"{did} ({v:+.3f} km)")
        reasons.append("; ".join(parts) if parts else "none (matches)")
    df["reason_for_difference"] = reasons
    df["original_billed_usd"] = df["original_km"] * ADVERTISER_RATE_USD_PER_KM
    df["corrected_billed_usd"] = df["corrected_km"] * ADVERTISER_RATE_USD_PER_KM
    df["advertiser_overbilling_usd"] = df["original_billed_usd"] - df["corrected_billed_usd"]
    df["driver_payout_error_usd"] = df["advertiser_overbilling_usd"] * DRIVER_PAYOUT_SHARE
    for c in ("original_km", "corrected_km", "difference_km"):
        df[c] = df[c].round(6)
    for c in ("original_billed_usd", "corrected_billed_usd", "advertiser_overbilling_usd", "driver_payout_error_usd"):
        df[c] = df[c].round(4)
    return df.sort_values(["driver_id", "report_date"]).reset_index(drop=True)


def financial_summary(ba: pd.DataFrame) -> dict:
    return {
        "rate_usd_per_km": ADVERTISER_RATE_USD_PER_KM,
        "driver_payout_share": DRIVER_PAYOUT_SHARE,
        "original_km": float(ba["original_km"].sum()),
        "corrected_km": float(ba["corrected_km"].sum()),
        "difference_km": float(ba["difference_km"].sum()),
        "difference_pct": float(ba["difference_km"].sum() / ba["corrected_km"].sum() * 100),
        "original_billed_usd": float(ba["original_billed_usd"].sum()),
        "corrected_billed_usd": float(ba["corrected_billed_usd"].sum()),
        "advertiser_overbilling_usd": float(ba["advertiser_overbilling_usd"].sum()),
        "driver_payout_error_usd": float(ba["driver_payout_error_usd"].sum()),
    }


def md_table(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append(floatfmt.format(v) if isinstance(v, float) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def defect_report_markdown(pings: pd.DataFrame, cfg: EngineConfig | None = None) -> str:
    cfg = cfg or EngineConfig()
    findings = detect_defects(pings, cfg)
    scan = anomaly_scan(pings, cfg)
    total = float(process(pings, cfg).daily["km"].sum())
    L = ["# Defect Report (generated by `python -m src.reporting`)", "",
         "> SYNTHETIC data. The baseline is an INTENTIONALLY DEFECTIVE reference written for this assessment - "
         "not any employer's production code.", "",
         f"Method: each defect is measured by re-introducing it into the corrected engine one at a time (ablation) "
         f"and comparing driver-day kilometres against the corrected result ({total:.3f} km in-zone in total). "
         f"Money uses the synthetic rate USD {ADVERTISER_RATE_USD_PER_KM:.2f}/km, driver payout {DRIVER_PAYOUT_SHARE:.0%}.", "",
         "## Ranking (by absolute driver-day exposure)", ""]
    rank = pd.DataFrame([{
        "Rank": i + 1, "ID": f.defect_id, "Severity": f.severity, "Priority": f.priority,
        "Records": f.records_affected, "Net km": round(f.net_km, 3), "Abs driver-day km": round(f.abs_driver_day_km, 3),
        "Advertiser USD": round(f.advertiser_impact_usd, 2), "Driver payout USD": round(f.driver_impact_usd, 2),
    } for i, f in enumerate(findings)])
    L += [md_table(rank), "", "Positive net km / USD = the defective logic OVER-bills the advertiser (and over-pays drivers); "
          "negative = under-billing.", "",
          "**Reading the numbers:** impacts are *marginal* (one defect re-introduced at a time). Rules overlap and compound, "
          "so the rows do not sum to the full baseline error of the combined defects (e.g. a 400 m off-road ping also implies "
          ">150 km/h, so removing only the off-road rule changes little). All eight together reproduce the baseline exactly "
          "(tests/test_regression.py::test_ablation_of_all_rules_reproduces_baseline_exactly).", "",
          "## Data anomalies found by the validator", ""]
    L += [f"- {k.replace('_', ' ')}: {v}" for k, v in scan.items() if k != "reject_reasons"]
    L += [f"- rejection reasons: {scan['reject_reasons']}", "", "## Findings", ""]
    for i, f in enumerate(findings, 1):
        L += [f"### {i}. {f.defect_id} - {f.title}", "",
              f"- **Severity / priority:** {f.severity} / {f.priority}",
              f"- **Violated rule:** {f.rule}",
              f"- **Root cause:** {f.root_cause}",
              f"- **Reproduction:** `python -c \"from src.reporting import *; from src.distance_calculator import *; p=load_pings(); "
              f"print(process(p, EngineConfig(**{DEFECTS[f.defect_id]['override']})).daily.km.sum() - process(p).daily.km.sum())\"` "
              f"(re-introduces only this defect); reproduced = {f.reproduced}",
              f"- **Records affected:** {f.records_affected}",
              f"- **Affected drivers:** {', '.join(f.affected_drivers) or 'none'}",
              f"- **Distance impact:** net {f.net_km:+.3f} km, absolute driver-day {f.abs_driver_day_km:.3f} km",
              f"- **Advertiser financial impact:** {f.advertiser_impact_usd:+.2f} USD; **driver payout impact:** {f.driver_impact_usd:+.2f} USD",
              "- **Evidence from the dataset:**"]
        L += [f"  - {e}" for e in f.evidence] or ["  - (none)"]
        L += ["- **Fix status:** fixed in `src/distance_calculator.py`; **Regression status:** covered by tests/test_regression.py", ""]
    return "\n".join(L)


def write_reports(reports_dir: Path | None = None) -> dict:
    """Regenerate before_after_comparison.csv and defect_report.md from the dataset."""
    from baseline.faulty_calculator import calculate_daily_distance
    reports_dir = reports_dir or ROOT / "reports"
    pings = load_pings()
    cfg = EngineConfig()
    base = calculate_daily_distance(pings, cfg.report_utc_offset_hours)
    ba = build_before_after(pings, base, cfg)
    ba.to_csv(reports_dir / "before_after_comparison.csv", index=False)
    (reports_dir / "defect_report.md").write_text(defect_report_markdown(pings, cfg))
    return financial_summary(ba)


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))
    import json
    print(json.dumps(write_reports(), indent=2))
